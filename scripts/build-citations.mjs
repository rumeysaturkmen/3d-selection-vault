// Builds data/citations.json: which papers in the vault cite which other papers in the vault.
//
// Sources, in order of preference:
//   1. data/openalex-references.txt — one line per paper:
//        <publication id> SELF <OpenAlex id> [ALSO <id> ...] REFS <OpenAlex ids it cites ...>
//      fetched from api.openalex.org (referenced_works). Extra OpenAlex ids for the same
//      paper (duplicate records) go after ALSO.
//   2. Survey coverage already in the vault: a survey listed as "surveyed" on a technique
//      is taken to cite the paper that introduced that technique. Used only for surveys
//      that OpenAlex has no reference list for.
// Run with: node scripts/build-citations.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const readDir = (d) =>
  readdirSync(join(root, d)).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(join(root, d, f), 'utf8')));
const pubs = new Map(readDir('data/publications').map((p) => [p.id, p]));
const techs = readDir('data/techniques');

const ownerOf = new Map(); // OpenAlex id -> publication id
const refsOf = new Map(); // publication id -> OpenAlex ids
for (const line of readFileSync(join(root, 'data/openalex-references.txt'), 'utf8').split('\n')) {
  const t = line.trim().split(/\s+/);
  if (t.length < 3 || !pubs.has(t[0])) continue;
  const pid = t[0];
  const refsAt = t.indexOf('REFS');
  const selfIds = t.slice(t.indexOf('SELF') + 1, refsAt < 0 ? undefined : refsAt).filter((x) => x !== 'ALSO');
  for (const w of selfIds) ownerOf.set(w, pid);
  refsOf.set(pid, refsAt < 0 ? [] : t.slice(refsAt + 1));
}

const edges = new Map();
const add = (from, to, source) => {
  if (from === to || !pubs.has(from) || !pubs.has(to)) return;
  const key = `${from}>${to}`;
  if (!edges.has(key)) edges.set(key, { from, to, source });
};

for (const [pid, refs] of refsOf) for (const w of refs) if (ownerOf.has(w)) add(pid, ownerOf.get(w), 'openalex');

const hasOpenAlexRefs = new Set([...refsOf].filter(([, r]) => r.length > 0).map(([p]) => p));
for (const t of techs) {
  const intro = t.publications.filter((p) => p.role === 'introduced').map((p) => p.publication);
  for (const s of t.publications.filter((p) => p.role === 'surveyed'))
    if (!hasOpenAlexRefs.has(s.publication)) for (const i of intro) add(s.publication, i, 'survey');
}

const list = [...edges.values()].sort((a, b) => (a.from + a.to).localeCompare(b.from + b.to));
writeFileSync(
  join(root, 'data/citations.json'),
  JSON.stringify(
    {
      $comment: 'Generated by scripts/build-citations.mjs. "from" cites "to". Do not edit by hand.',
      coverage: { withReferenceData: hasOpenAlexRefs.size, publications: pubs.size },
      citations: list,
    },
    null,
    1,
  ) + '\n',
);
const linked = new Set(list.flatMap((e) => [e.from, e.to]));
console.log(`${list.length} citations (${list.filter((e) => e.source === 'openalex').length} from OpenAlex) among ${linked.size} of ${pubs.size} papers; ${hasOpenAlexRefs.size} papers have reference data`);
